/// The English name of a two-letter code in any case, or None for a code that is not one.
pub fn english_name(code: &str) -> Option<&'static str> {
    index_of(code).map(|index| COUNTRIES[index].1)
}

/// The code as it is kept, upper case, when it is a known country.
pub fn normalize(code: &str) -> Option<&'static str> {
    index_of(code).map(|index| COUNTRIES[index].0)
}

fn index_of(code: &str) -> Option<usize> {
    let code = code.trim().to_ascii_uppercase();
    COUNTRIES
        .binary_search_by(|(known, _)| (*known).cmp(code.as_str()))
        .ok()
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;

    #[test]
    fn every_code_is_two_upper_case_letters_in_order_and_every_name_is_unique() {
        assert_eq!(COUNTRIES.len(), 249);
        for (code, name) in COUNTRIES {
            assert!(
                code.len() == 2 && code.chars().all(|c| c.is_ascii_uppercase()),
                "{code}"
            );
            assert!(!name.trim().is_empty() && !name.contains(','), "{code} {name}");
        }
        assert!(COUNTRIES.windows(2).all(|pair| pair[0].0 < pair[1].0));
        let names: HashSet<&str> = COUNTRIES.iter().map(|(_, name)| *name).collect();
        assert_eq!(names.len(), COUNTRIES.len());
    }

    #[test]
    fn a_code_names_its_country_in_any_case() {
        assert_eq!(english_name("ES"), Some("Spain"));
        assert_eq!(english_name("kr"), Some("South Korea"));
        assert_eq!(english_name(" gb "), Some("United Kingdom"));
        assert_eq!(english_name("XX"), None);
        assert_eq!(english_name("ESP"), None);
        assert_eq!(normalize("jp"), Some("JP"));
        assert_eq!(normalize(""), None);
    }
}
